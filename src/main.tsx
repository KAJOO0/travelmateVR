import { StrictMode, Suspense } from 'react';
import { createRoot } from 'react-dom/client';
import { createBrowserRouter, RouterProvider } from 'react-router-dom';
import { Amplify } from 'aws-amplify';
import { Hub } from 'aws-amplify/utils';
import 'aws-amplify/auth/enable-oauth-listener'; // activates Google sign-in's redirect handling (harmless no-op without it configured)
import '@/i18n';
import '@/services/overlays';
import '@/styles/tokens.css';
import '@/styles/base.css';
import '@/styles/layout.css';
import { routes } from '@/app/routes';
import { initPwa } from '@/app/pwa';
import { PreferencesProvider } from '@/app/providers/PreferencesProvider';
import { WishlistProvider } from '@/app/providers/WishlistProvider';
import { syncSessionFromRedirect } from '@/services/account';

// amplify_outputs.json is generated by `npx ampx sandbox` / the Amplify Console's backend
// build phase — it doesn't exist until a real backend has been deployed. A glob import
// (rather than a static one) means its absence never breaks mock-mode dev/build: the glob
// simply matches nothing, and real-backend features (catalog/account in 'http' mode) are
// the only things that need it.
const outputsModules = import.meta.glob<{ default: Record<string, unknown> }>('../amplify_outputs.json', { eager: true });
const outputs = Object.values(outputsModules)[0]?.default;
if (outputs) Amplify.configure(outputs);

// Google sign-in is a full browser redirect — the click that started it never gets to finish
// running. This is how the app notices a redirect sign-in actually completed (Hub fires
// 'signInWithRedirect' specifically for this flow, not for regular email/password sign-in,
// so it can't double-fire or race with the normal sign-in path).
Hub.listen('auth', ({ payload }) => {
  if (payload.event === 'signInWithRedirect') void syncSessionFromRedirect();
});

initPwa();
const router = createBrowserRouter(routes);

createRoot(document.getElementById('root')!).render(
  <StrictMode>
    <Suspense fallback={null}>
      <PreferencesProvider>
        <WishlistProvider>
          <RouterProvider router={router} />
        </WishlistProvider>
      </PreferencesProvider>
    </Suspense>
  </StrictMode>
);
