import { StrictMode, Suspense } from 'react';
import { createRoot } from 'react-dom/client';
import { createBrowserRouter, RouterProvider } from 'react-router-dom';
import { Amplify } from 'aws-amplify';
import { Hub } from 'aws-amplify/utils';
import 'aws-amplify/auth/enable-oauth-listener'; // activates Google sign-in's redirect handling (harmless no-op without it configured)
import '@/i18n';
import '@/services/overlays';
import '@/styles/tokens.css';
import '@/styles/base.css';
import '@/styles/layout.css';
import { routes } from '@/app/routes';
import { initPwa } from '@/app/pwa';
import { PreferencesProvider } from '@/app/providers/PreferencesProvider';
import { WishlistProvider } from '@/app/providers/WishlistProvider';
import { syncSessionFromRedirect } from '@/services/account';

// amplify_outputs.json is generated by `npx ampx sandbox` / the Amplify Console's backend
// build phase — it doesn't exist until a real backend has been deployed. A glob import
// (rather than a static one) means its absence never breaks mock-mode dev/build: the glob
// simply matches nothing, and real-backend features (catalog/account in 'http' mode) are
// the only things that need it.
const outputsModules = import.meta.glob<{ default: Record<string, unknown> }>('../amplify_outputs.json', { eager: true });
const outputs = Object.values(outputsModules)[0]?.default;
if (outputs) {
  // Upstream bug workaround: once amplify/backend.ts overrides the Hosted UI onto a custom
  // domain (auth.travelmatevr.com) via the CfnUserPoolDomain escape hatch, the auth
  // construct's own output-generation code still computes oauth.domain as
  // `${domainName}.auth.${region}.amazoncognito.com` — written for the Cognito-prefix case,
  // unaware we replaced domainName with a full custom FQDN. Confirmed live: the deployed
  // bundle actually shipped "auth.travelmatevr.com.auth.eu-west-3.amazoncognito.com", a
  // domain that doesn't exist — which is why Google sign-in hung (signInWithRedirect was
  // navigating the browser to that nonexistent host). The underlying Cognito resource itself
  // is correct; only this one generated config value is wrong, so patch it here rather than
  // reaching back into third-party construct internals. If the custom domain ever changes,
  // update this string to match.
  const oauth = (outputs as { auth?: { oauth?: { domain?: string } } }).auth?.oauth;
  if (oauth?.domain?.endsWith('.amazoncognito.com')) oauth.domain = 'auth.travelmatevr.com';
  Amplify.configure(outputs);
}

const router = createBrowserRouter(routes);

// Google sign-in is a full browser redirect — the click that started it never gets to finish
// running. This is how the app notices a redirect sign-in actually completed (Hub fires
// 'signInWithRedirect' specifically for this flow, not for regular email/password sign-in,
// so it can't double-fire or race with the normal sign-in path).
Hub.listen('auth', ({ payload }) => {
  if (payload.event === 'signInWithRedirect') {
    // The OAuth round-trip always lands back on the bare registered callback URL (the
    // homepage), never wherever the user actually meant to go — unlike the normal
    // email/password sign-in form, which already navigates to /account itself. Without this,
    // a successful Google sign-in looked like nothing happened: the session was set, but
    // nothing ever took the user anywhere to see it.
    void syncSessionFromRedirect().then(signedIn => { if (signedIn) void router.navigate('/account'); });
  }
  // Without this, a failed federated sign-in (wrong IdP scopes, Cognito rejecting the
  // federated user, etc.) fails completely silently — the page that started the redirect is
  // long gone by the time Cognito reports back, and nothing else listens for this event.
  else if (payload.event === 'signInWithRedirect_failure') console.error('Google sign-in failed:', payload.data?.error);
});

initPwa();

createRoot(document.getElementById('root')!).render(
  <StrictMode>
    <Suspense fallback={null}>
      <PreferencesProvider>
        <WishlistProvider>
          <RouterProvider router={router} />
        </WishlistProvider>
      </PreferencesProvider>
    </Suspense>
  </StrictMode>
);
